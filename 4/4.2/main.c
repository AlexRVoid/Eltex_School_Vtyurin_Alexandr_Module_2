#include "pqueue.h"
#include <stdio.h>
#include <stdlib.h>
#include <time.h>

static void print_message(const char *action, const Message *m)
{
    printf("%-20s | Приоритет: %3u | SeqID: #%-3u | Данные: \"%s\"\n",
           action, m->priority, m->seq_id, m->data);
}

int main(void)
{
    PriorityQueue pq;
    pqueue_init(&pq);
    srand((unsigned int)time(NULL));

    printf("======================================================================\n");
    printf("     ТЕСТИРОВАНИЕ ОЧЕРЕДИ С ПРИОРИТЕТОМ (ДИАПАЗОН 0..255)            \n");
    printf("======================================================================\n\n");

    /* ------------------------------------------------------------------ */
    /* 1. Имитация генерации сообщений с различными приоритетами          */
    /* ------------------------------------------------------------------ */
    printf("[1] Генерация сообщений в очередь...\n");

    /* Специально добавляем несколько сообщений с одинаковым приоритетом 100 для проверки FIFO */
    pqueue_push(&pq, 100, "Пакет А (приоритет 100, первый)");
    pqueue_push(&pq, 100, "Пакет Б (приоритет 100, второй)");
    pqueue_push(&pq, 100, "Пакет В (приоритет 100, третий)");

    /* Граничные и критические приоритеты */
    pqueue_push(&pq, 0,   "Фоновая задача (приоритет 0)");
    pqueue_push(&pq, 255, "Критическая авария (приоритет 255)");
    pqueue_push(&pq, 255, "Системное прерывание (приоритет 255)");
    pqueue_push(&pq, 42,  "Телеметрия (приоритет 42)");
    pqueue_push(&pq, 180, "Сетевой пакет (приоритет 180)");
    pqueue_push(&pq, 220, "Команда управления (приоритет 220)");
    pqueue_push(&pq, 15,  "Журнал аудита (приоритет 15)");

    /* Случайные сообщения */
    for (int i = 1; i <= 5; i++) {
        uint8_t rand_pri = (uint8_t)(rand() % 256);
        char buf[64];
        snprintf(buf, sizeof(buf), "Случайное сообщение %d", i);
        pqueue_push(&pq, rand_pri, buf);
    }

    printf("Всего сгенерировано сообщений в очереди: %zu\n\n", pqueue_size(&pq));

    /* ------------------------------------------------------------------ */
    /* 2. Извлечение первого в очереди (наивысший приоритет)               */
    /* ------------------------------------------------------------------ */
    printf("[2] Извлечение первых 3 элементов (наивысший приоритет + FIFO):\n");
    Message m;
    for (int i = 0; i < 3; i++) {
        if (pqueue_pop_first(&pq, &m)) {
            print_message("pop_first()", &m);
        }
    }
    printf("Элементов в очереди осталось: %zu\n\n", pqueue_size(&pq));

    /* ------------------------------------------------------------------ */
    /* 3. Извлечение с указанным приоритетом (точное совпадение)          */
    /* ------------------------------------------------------------------ */
    printf("[3] Извлечение элементов с ТОЧНЫМ приоритетом:\n");

    /* Запрашиваем приоритет 100 — проверяем сохранение FIFO между Пакетами А и Б */
    printf("-> Запрос приоритета 100:\n");
    if (pqueue_pop_by_priority(&pq, 100, &m)) {
        print_message("pop_exact(100)", &m);
    }
    if (pqueue_pop_by_priority(&pq, 100, &m)) {
        print_message("pop_exact(100)", &m);
    }

    /* Запрос несуществующего приоритета */
    printf("-> Запрос приоритета 250 (заведомо отсутствует):\n");
    if (!pqueue_pop_by_priority(&pq, 250, &m)) {
        printf("   [OK] Элементов с приоритетом 250 в очереди не обнаружено.\n");
    }
    printf("Элементов в очереди осталось: %zu\n\n", pqueue_size(&pq));

    /* ------------------------------------------------------------------ */
    /* 4. Извлечение с приоритетом не ниже чем заданный (>= threshold)    */
    /* ------------------------------------------------------------------ */
    printf("[4] Извлечение с условием: приоритет >= 150:\n");
    while (pqueue_pop_ge_priority(&pq, 150, &m)) {
        print_message("pop_ge(>=150)", &m);
    }
    printf("   [OK] Больше нет элементов с приоритетом >= 150.\n");
    printf("Элементов в очереди осталось: %zu\n\n", pqueue_size(&pq));

    /* ------------------------------------------------------------------ */
    /* 5. Выборка всех оставшихся элементов до опустошения очереди        */
    /* ------------------------------------------------------------------ */
    printf("[5] Выборка всех оставшихся сообщений из очереди по порядку:\n");
    while (pqueue_pop_first(&pq, &m)) {
        print_message("pop_remaining()", &m);
    }

    printf("\nИтоговое количество элементов в очереди: %zu (очередь пуста)\n", pqueue_size(&pq));

    /* Корректное завершение */
    pqueue_free_all(&pq);
    return 0;
}